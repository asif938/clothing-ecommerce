import { ForbiddenException, Injectable } from "@nestjs/common";
import type { Media } from "@clothing/db";
import { getMediaUrl } from "@clothing/shared/media";
import { PrismaService } from "../prisma/prisma.service";
import { SettingsService } from "../settings/settings.service";
import { MediaProvidersService } from "../media/media-providers.service";
import type { MediaVariantMap } from "../media/media-driver";
import { buildProductFeedXml, type FeedItem } from "./feed-xml";

const FEED_IMAGE_WIDTH = 800;

/** Product feeds (docs/PROJECT_SPEC.md §10.5) — generated on demand (not pre-generated by a job, see docs/DECISIONS.md), gated by `feeds.secretToken` since Meta/Google fetch feed URLs unauthenticated. */
@Injectable()
export class FeedsService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly settings: SettingsService,
    private readonly mediaProviders: MediaProvidersService,
  ) {}

  async assertAccessible(token: string | undefined): Promise<void> {
    const enabled = await this.settings.getValue<boolean>("feeds.enabled");
    const secret = await this.settings.getValue<string | null>("feeds.secretToken");
    if (!enabled || !secret || !token || token !== secret) {
      throw new ForbiddenException("Product feed is not available");
    }
  }

  private async resolveImageUrl(media: Media | null): Promise<string | null> {
    if (!media) return null;
    const driver = await this.mediaProviders.resolveDriverForAsset(media);
    const ref = driver.toMediaRef({ ...media, variants: media.variants as MediaVariantMap | null });
    return getMediaUrl(ref, { width: FEED_IMAGE_WIDTH });
  }

  async buildXml(): Promise<string> {
    const [brandName, products] = await Promise.all([
      this.settings.getValue<{ bn: string; en: string }>("brand.name"),
      this.prisma.product.findMany({
        where: { status: "active", deletedAt: null },
        include: {
          media: { include: { media: true }, orderBy: { position: "asc" }, take: 1 },
          variants: { where: { isActive: true }, include: { inventoryLevels: { select: { available: true } } } },
        },
      }),
    ]);

    const storefrontUrl = process.env.STOREFRONT_URL ?? "";
    const brand = brandName?.en ?? brandName?.bn ?? "";
    const items: FeedItem[] = [];

    for (const product of products) {
      const imageLink = await this.resolveImageUrl(product.media[0]?.media ?? null);
      const title = this.localizedText(product.title) ?? product.slug;
      const description = this.localizedText(product.shortDescription) ?? this.localizedText(product.description) ?? title;
      const link = `${storefrontUrl}/p/${product.slug}`;

      for (const variant of product.variants) {
        const inStock = variant.inventoryLevels.some((l) => l.available > 0);
        items.push({
          id: variant.sku,
          title,
          description,
          link,
          imageLink,
          availability: inStock ? "in stock" : "out of stock",
          priceAmount: variant.price,
          priceCurrency: "BDT",
          brand,
          itemGroupId: product.id,
          variantLabel: null,
        });
      }
    }

    return buildProductFeedXml({ title: brand, link: storefrontUrl, description: `${brand} product catalog`, items });
  }

  private localizedText(value: unknown): string | null {
    if (!value || typeof value !== "object") return null;
    const text = value as { en?: string; bn?: string };
    return text.en ?? text.bn ?? null;
  }
}
